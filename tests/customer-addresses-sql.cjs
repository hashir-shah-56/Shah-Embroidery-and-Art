// Executes the actual migration/RPC/RLS in local PostgreSQL. No remote changes.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require(process.env.PGLITE_MODULE || path.join(require('node:os').tmpdir(), 'shah-profile-sql-tests/node_modules/@electric-sql/pglite'));
(async () => {
  const db = new PGlite();
  const a = '11111111-1111-4111-8111-111111111111', b = '22222222-2222-4222-8222-222222222222';
  const draft = { label: 'Home', full_name: 'Customer One', phone: '+92 300 1234567', address_line_1: '12 Main Street / #3', city: 'Lahore', postal_code: '54000', country: 'Pakistan', is_default: false };
  const rpc = async (action, id = null, details = draft) => (await db.query('select * from public.customer_address_mutate($1, $2, $3::jsonb)', [action, id, JSON.stringify(details)])).rows;
  const asUser = id => db.exec(`reset role; set role authenticated; select set_config('request.jwt.claim.sub', '${id}', false);`);
  try {
    await db.exec(`create role anon; create role authenticated; create schema auth;
      create table auth.users (id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid$$;
      grant usage on schema auth to anon, authenticated;
      insert into auth.users values ('${a}'), ('${b}');`);
    const sql = fs.readFileSync(path.join(__dirname, '../supabase/customer-addresses.sql'), 'utf8');
    await db.exec(sql);
    await asUser(b); const foreign = (await rpc('save'))[0];
    await db.exec('reset role');
    await db.exec('create policy broad_existing on public.addresses for all to authenticated using (true) with check (true)');
    await db.exec(sql);
    assert.equal((await db.query('select count(*)::int as n from public.addresses')).rows[0].n, 1);
    assert.equal((await db.query("select relrowsecurity from pg_class where oid = 'public.addresses'::regclass")).rows[0].relrowsecurity, true);
    await asUser(a);
    let rows = await rpc('save', null, { ...draft, user_id: b });
    const first = rows[0]; assert.equal(first.user_id, a); assert.equal(first.is_default, true);
    rows = await rpc('save', null, { ...draft, label: 'Work' });
    const second = rows.find(row => row.id !== first.id);
    assert.equal(second.is_default, false);
    rows = await rpc('default', second.id); assert.equal(rows[0].id, second.id);
    rows = await rpc('save', second.id, { ...draft, label: 'Updated', city: 'London', country: 'United Kingdom', postal_code: 'SW1A 1AA', is_default: true });
    assert.equal(rows.length, 2); assert.equal(rows[0].id, second.id); assert.equal(rows[0].postal_code, 'SW1A 1AA');
    await assert.rejects(rpc('save', null, { ...draft, phone: 'bad', is_default: true }), /check constraint/);
    assert.equal((await db.query('select id from public.addresses where is_default')).rows[0].id, second.id, 'failed save rolls default change back');
    await assert.rejects(db.query('update public.addresses set is_default = true where id = $1', [first.id]), /unique constraint/);
    assert.equal((await db.query('select * from public.addresses where user_id = $1', [b])).rows.length, 0);
    assert.equal((await db.query('update public.addresses set label = $1 where id = $2 returning *', ['Intruder', foreign.id])).rows.length, 0);
    assert.equal((await db.query('delete from public.addresses where id = $1 returning *', [foreign.id])).rows.length, 0);
    await assert.rejects(db.query('update public.addresses set user_id = $1 where id = $2', [b, first.id]), /immutable/);
    await assert.rejects(db.query(`insert into public.addresses(user_id,full_name,phone,address_line_1,city,country) values ($1,'Bad Actor','+92 300 1234567','12 Main Road','Lahore','Pakistan')`, [b]), /row-level security/);
    for (const action of ['save','delete','default']) await assert.rejects(rpc(action, foreign.id), /Address unavailable/);
    console.log('PASS: idempotent setup, immutable UUID ownership, all RLS operations, foreign RPC denial and default rollback/unique index');
    rows = await rpc('save', second.id, { ...draft, is_default: false });
    assert.equal(rows[0].id, first.id, 'unchecking promotes other address');
    rows = await rpc('delete', second.id); assert.equal(rows[0].id, first.id);
    rows = await rpc('save', null, { ...draft, label: 'Newest' });
    const newest = rows.find(row => row.id !== first.id);
    rows = await rpc('delete', first.id); assert.equal(rows[0].id, newest.id); assert.equal(rows[0].is_default, true);
    assert.equal((await rpc('delete', newest.id)).length, 0);
    await asUser(b); assert.equal((await db.query('select * from public.addresses')).rows[0].id, foreign.id);
    await db.exec("reset role; set role anon; select set_config('request.jwt.claim.sub', '', false)");
    await assert.rejects(db.query('select * from public.addresses'), /permission denied/);
    await assert.rejects(rpc('save'), /permission denied/);
    await asUser(''); await assert.rejects(rpc('save'), /Authentication required/);
    await db.exec(`reset role; delete from auth.users where id = '${b}'`);
    assert.equal((await db.query('select count(*)::int as n from public.addresses')).rows[0].n, 0);
    console.log('PASS: first default, edit/default switching, default/non-default/final deletion, deterministic promotion, anonymous denial and Auth cascade');
  } finally { await db.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
